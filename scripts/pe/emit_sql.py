"""Emit the migration that loads database/pe/<form>.v<N>.json into pe_form_definitions and adds the Form PE submenu.
usage: python3 emit_sql.py <form> <version> <migration_no> <menu label> <menu order> <icon>"""
import json, os, sys
from pe_core import ROOT
form, ver, no, label, order, icon = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4], int(sys.argv[5]), sys.argv[6]
schema = json.load(open(os.path.join(ROOT, 'database', 'pe', f'{form}.v{ver}.json')))
body = json.dumps(schema, ensure_ascii=False, separators=(',', ':'))
assert '$pe$' not in body
name = f'{no}_pe_form_{form}.sql'
sub = json.dumps({'id': f'sub_pe_{form}', 'label': label, 'icon': icon, 'href': f'/pe/{form}', 'order': order, 'enabled': True}, ensure_ascii=False)
sql = f"""-- {no}: Form PE {label} v{ver} (generated by scripts/pe/emit_sql.py from database/pe/{form}.v{ver}.json; do not edit by hand).
-- Rollback: database/rollback/{no}_rollback.sql
INSERT INTO pe_form_definitions (form_key, version, disease_id, title, schema)
SELECT '{form}', {ver}, (SELECT id FROM master_diseases WHERE code = '{schema['disease_code']}'), $pe${schema['title']}$pe$, $pe${body}$pe$::jsonb
ON CONFLICT (form_key, version) DO NOTHING;
UPDATE app_settings SET value = (
  SELECT jsonb_agg(CASE WHEN g->>'id' = 'grp_form_pe'
           THEN jsonb_set(g, '{{items,0,subItems}}', (g->'items'->0->'subItems') || '[{sub}]'::jsonb)
           ELSE g END ORDER BY ord)
  FROM jsonb_array_elements(value::jsonb) WITH ORDINALITY AS t(g, ord))::text, updated_at = now()
WHERE key = 'navigation_menu';
"""
open(os.path.join(ROOT, 'database', 'init', name), 'w').write(sql)
rb = f"""-- Rollback {no}: remove Form PE {label} (its PE cases, clusters and definition rows) and its submenu.
DELETE FROM pe_cases WHERE form_key = '{form}';
DELETE FROM pe_clusters WHERE form_key = '{form}';
DELETE FROM pe_counters WHERE form_key = '{form}';
DELETE FROM pe_form_definitions WHERE form_key = '{form}';
UPDATE app_settings SET value = (
  SELECT jsonb_agg(CASE WHEN g->>'id' = 'grp_form_pe'
           THEN jsonb_set(g, '{{items,0,subItems}}', COALESCE((SELECT jsonb_agg(s) FROM jsonb_array_elements(g->'items'->0->'subItems') s WHERE s->>'id' <> 'sub_pe_{form}'), '[]'::jsonb))
           ELSE g END ORDER BY ord)
  FROM jsonb_array_elements(value::jsonb) WITH ORDINALITY AS t(g, ord))::text, updated_at = now()
WHERE key = 'navigation_menu';
DELETE FROM schema_migrations WHERE filename = '{name}';
"""
open(os.path.join(ROOT, 'database', 'rollback', f'{no}_rollback.sql'), 'w').write(rb)
print(name, len(sql))
